    'ombudsman'
);

-- ---------------------------------------------------------------------------
-- Papéis e permissões expansíveis
-- ---------------------------------------------------------------------------

CREATE TABLE public.roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    description text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.role_permissions (
    role_id integer NOT NULL REFERENCES public.roles(id) ON DELETE RESTRICT,
    permission_id integer NOT NULL REFERENCES public.permissions(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (role_id, permission_id)
);

-- ---------------------------------------------------------------------------
-- Usuários autenticados e sessões de autenticação.
-- O público/paciente não é cadastrado como usuário.
-- Há no máximo uma sessão não revogada por usuário; abas no mesmo navegador
-- compartilham a mesma sessão/cookies (não há bloqueio de abas no frontend).
-- ---------------------------------------------------------------------------

CREATE TABLE public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id integer NOT NULL REFERENCES public.roles(id) ON DELETE RESTRICT,
    full_name text NOT NULL,
    email text NOT NULL,
    password_hash text NOT NULL,
    must_change_password boolean NOT NULL DEFAULT false,
    temporary_password_expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT users_temporary_password_expiry_check
        CHECK (must_change_password OR temporary_password_expires_at IS NULL)
);

-- O e-mail continua reservado mesmo quando a conta está desativada.
CREATE UNIQUE INDEX users_email_case_insensitive_uq
    ON public.users (lower(btrim(email)));
CREATE INDEX users_deleted_at_idx ON public.users (deleted_at);
CREATE INDEX users_role_id_idx ON public.users (role_id);

CREATE TABLE public.auth_sessions (
    -- UUID identifica a sessão de autenticação.
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    -- Token CSRF aleatório (pelo menos 32 bytes de entropia) estável durante
    -- a sessão. O backend precisa recuperá-lo após reload; nunca registrar em logs.
    csrf_token text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Última atividade válida da aplicação; a API limita escritas a cada 5 min.
    last_used_at timestamptz,
    -- Expiração absoluta, no máximo 24 horas depois de created_at.
    -- A inatividade de 12 horas é verificada pela API usando last_used_at/created_at.
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CONSTRAINT auth_sessions_expiry_check CHECK (expires_at > created_at),
    CONSTRAINT auth_sessions_csrf_token_length_check CHECK (length(csrf_token) >= 32)
);

CREATE INDEX auth_sessions_user_id_idx ON public.auth_sessions (user_id);
-- Garantia no banco: somente um login não revogado por usuário.
-- O serviço revoga todas as sessões anteriores não revogadas (inclusive expiradas)
-- antes de inserir a nova, na mesma transação.
CREATE UNIQUE INDEX auth_sessions_one_unrevoked_per_user_uq
    ON public.auth_sessions (user_id)
    WHERE revoked_at IS NULL;
CREATE INDEX auth_sessions_active_expiry_idx
    ON public.auth_sessions (expires_at)
    WHERE revoked_at IS NULL;

-- Histórico de refresh tokens: os valores originais nunca são armazenados.
-- O token é aleatório/opaco e a API persiste somente SHA-256 do valor.
CREATE TABLE public.auth_refresh_tokens (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id uuid NOT NULL
        REFERENCES public.auth_sessions(id) ON DELETE RESTRICT,
    token_hash text NOT NULL,
    issued_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    replaced_by_token_id uuid,
    CONSTRAINT auth_refresh_tokens_id_session_uq UNIQUE (id, session_id),
    CONSTRAINT auth_refresh_tokens_replacement_same_session_fk
        FOREIGN KEY (replaced_by_token_id, session_id)
        REFERENCES public.auth_refresh_tokens(id, session_id) ON DELETE RESTRICT,
    CONSTRAINT auth_refresh_tokens_hash_uq UNIQUE (token_hash),
    CONSTRAINT auth_refresh_tokens_expiry_check CHECK (expires_at > issued_at),
    CONSTRAINT auth_refresh_tokens_consumed_check
        CHECK (consumed_at IS NULL OR consumed_at >= issued_at),
    CONSTRAINT auth_refresh_tokens_not_self_replaced_check
        CHECK (replaced_by_token_id IS NULL OR replaced_by_token_id <> id)
);

CREATE INDEX auth_refresh_tokens_session_issued_idx
    ON public.auth_refresh_tokens (session_id, issued_at DESC);
-- Um token não consumido por sessão. Tokens consumidos permanecem para detectar replay.
CREATE UNIQUE INDEX auth_refresh_tokens_one_unconsumed_per_session_uq
    ON public.auth_refresh_tokens (session_id)
    WHERE consumed_at IS NULL;

-- ---------------------------------------------------------------------------
-- Setores e histórico dos vínculos gestor-setor
-- O status "ativo/em preparação" é calculado pela API. deleted_at representa
-- somente a desativação (soft delete) do setor.
-- ---------------------------------------------------------------------------

CREATE TABLE public.sectors (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL,
    name text NOT NULL,
    created_by_user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

-- A API normaliza códigos (trim, caixa e acentos) antes de persistir.
-- Este índice também impede colisões apenas por diferença de caixa/espaços externos.
CREATE UNIQUE INDEX sectors_code_normalized_uq
    ON public.sectors (lower(btrim(code)));
CREATE INDEX sectors_deleted_at_idx ON public.sectors (deleted_at);

CREATE TABLE public.user_sector_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    sector_id integer NOT NULL REFERENCES public.sectors(id) ON DELETE RESTRICT,
    assigned_at timestamptz NOT NULL DEFAULT now(),
    assigned_by_user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    unassigned_at timestamptz,
    unassigned_by_user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    CONSTRAINT user_sector_assignment_dates_check
        CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);

CREATE UNIQUE INDEX user_sector_one_active_assignment_uq
    ON public.user_sector_assignments (user_id, sector_id)
    WHERE unassigned_at IS NULL;
CREATE INDEX user_sector_assignments_sector_idx
    ON public.user_sector_assignments (sector_id, unassigned_at);
CREATE INDEX user_sector_assignments_user_idx
    ON public.user_sector_assignments (user_id, unassigned_at);

-- ---------------------------------------------------------------------------
-- Perguntas e suas versões imutáveis
-- question_kind='sector': pertence a um setor.
-- question_kind='standard': pergunta padrão, comum ou NPS (is_nps=true).
-- Edição de texto gera nova linha em question_versions. Reordenação e
-- desativação não geram nova versão.
-- ---------------------------------------------------------------------------

CREATE TABLE public.questions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_kind public.question_kind NOT NULL,
    scope public.question_scope NOT NULL,
    sector_id integer REFERENCES public.sectors(id) ON DELETE RESTRICT,
    is_nps boolean NOT NULL DEFAULT false,
    display_order integer NOT NULL DEFAULT 1,
    created_by_user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT questions_kind_scope_check CHECK (
        (
            question_kind = 'sector'
            AND sector_id IS NOT NULL
            AND scope = 'sector_only'
            AND is_nps = false
        )
        OR
        (
            question_kind = 'standard'
            AND sector_id IS NULL
            AND scope IN ('all_sectors', 'selected_sectors')
        )
    ),
    CONSTRAINT questions_order_positive_check CHECK (display_order >= 1)
);

CREATE INDEX questions_sector_order_idx
    ON public.questions (sector_id, display_order)
    WHERE question_kind = 'sector' AND deleted_at IS NULL;
CREATE INDEX questions_active_scope_idx
    ON public.questions (scope, is_nps)
    WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX questions_active_sector_order_uq
    ON public.questions (sector_id, display_order)
    WHERE question_kind = 'sector' AND deleted_at IS NULL;

-- Só pode existir uma pergunta NPS global vigente por vez.
CREATE UNIQUE INDEX questions_one_active_global_nps_uq
    ON public.questions (is_nps)
    WHERE is_nps = true AND scope = 'all_sectors' AND deleted_at IS NULL;

CREATE TABLE public.question_versions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE RESTRICT,
    version_number integer NOT NULL,
    text text NOT NULL,
    is_current boolean NOT NULL DEFAULT true,
    created_by_user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT question_versions_number_positive_check CHECK (version_number >= 1),
    CONSTRAINT question_versions_question_version_uq UNIQUE (question_id, version_number),
    -- Necessário para a FK composta dos itens congelados de uma sessão.
    CONSTRAINT question_versions_id_question_uq UNIQUE (id, question_id)
);

CREATE UNIQUE INDEX question_versions_one_current_uq
    ON public.question_versions (question_id)
    WHERE is_current = true;
CREATE INDEX question_versions_question_idx
    ON public.question_versions (question_id, version_number DESC);

-- Associação por setor de perguntas padrão comuns. Para perguntas de escopo
-- global, a API cria associações para os setores atuais e para novos setores.
-- O NPS usa a tabela separada sector_nps_assignments.
CREATE TABLE public.question_sector_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE RESTRICT,
    sector_id integer NOT NULL REFERENCES public.sectors(id) ON DELETE RESTRICT,
    assignment_source public.question_assignment_source NOT NULL,
    display_order integer NOT NULL,
    assigned_at timestamptz NOT NULL DEFAULT now(),
    assigned_by_user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    ended_at timestamptz,
    CONSTRAINT question_sector_assignment_order_check CHECK (display_order >= 1),
    CONSTRAINT question_sector_assignment_dates_check
        CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);

CREATE UNIQUE INDEX question_sector_assignment_active_question_uq
    ON public.question_sector_assignments (question_id, sector_id)
    WHERE ended_at IS NULL;
CREATE UNIQUE INDEX question_sector_assignment_active_order_uq
    ON public.question_sector_assignments (sector_id, display_order)
    WHERE ended_at IS NULL;
CREATE INDEX question_sector_assignments_sector_idx
    ON public.question_sector_assignments (sector_id, ended_at, display_order);

-- Histórico dos NPS efetivamente vinculados a cada setor. A restrição parcial
-- impede mais de um NPS vigente por setor. Uma associação global é materializada
-- para setores atuais; a API a cria também quando um novo setor é cadastrado.
-- Para substituir um NPS de um setor, o service encerra o vínculo vigente
-- antes de inserir o novo, tudo dentro da mesma transação. Se algo falhar, a
-- transação restaura o vínculo anterior, e nunca se confirma um estado parcial.
CREATE TABLE public.sector_nps_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id integer NOT NULL REFERENCES public.sectors(id) ON DELETE RESTRICT,
    question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE RESTRICT,
    assignment_source public.nps_assignment_source NOT NULL,
    assigned_at timestamptz NOT NULL DEFAULT now(),
    assigned_by_user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    ended_at timestamptz,
    CONSTRAINT sector_nps_assignment_dates_check
        CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);

CREATE UNIQUE INDEX sector_nps_one_current_per_sector_uq
    ON public.sector_nps_assignments (sector_id)
    WHERE ended_at IS NULL;
CREATE INDEX sector_nps_question_idx
    ON public.sector_nps_assignments (question_id, ended_at);

-- ---------------------------------------------------------------------------
-- Planilhas versionadas, faixas de turno e escala de funcionários
-- O CSV original nunca é armazenado. Faixas e atribuições normalizadas são
-- gravadas apenas depois da validação completa do upload.
-- ---------------------------------------------------------------------------

-- O service de upload deve trocar a versão corrente dentro de transação:
-- primeiro colocar a versão atual em is_current=false e então inserir/marcar
-- a nova versão como corrente. O índice parcial impede duas correntes ao mesmo
-- tempo; se a operação falhar, a transação restaura a versão anterior.
CREATE TABLE public.shift_sheet_versions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_number integer NOT NULL UNIQUE,
    uploaded_by_user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    valid_from timestamptz NOT NULL DEFAULT now(),
    is_current boolean NOT NULL DEFAULT false,
    CONSTRAINT shift_sheet_version_number_check CHECK (version_number >= 1)
);

CREATE UNIQUE INDEX shift_sheet_one_current_version_uq
    ON public.shift_sheet_versions (is_current)
    WHERE is_current = true;
CREATE INDEX shift_sheet_versions_valid_from_idx
    ON public.shift_sheet_versions (valid_from DESC);

-- Regra de interpretação horária adotada pelo validador/busca da API:
-- Regra temporal: ends_at < starts_at significa que a faixa cruza a meia-noite.
-- starts_at == ends_at é inválido (não representa 24 horas). O intervalo é
-- inclusivo no início e exclusivo no fim. O upload valida cobertura de 24 h e
-- ausência de sobreposição; a API também trata corretamente a virada de dia.
CREATE TABLE public.sector_shift_ranges (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_sheet_version_id integer NOT NULL
        REFERENCES public.shift_sheet_versions(id) ON DELETE RESTRICT,
    sector_id integer NOT NULL REFERENCES public.sectors(id) ON DELETE RESTRICT,
    shift_name text NOT NULL,
    starts_at time NOT NULL,
    ends_at time NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT sector_shift_range_composite_uq
        UNIQUE (id, shift_sheet_version_id, sector_id),
    CONSTRAINT sector_shift_range_duplicate_uq
        UNIQUE (shift_sheet_version_id, sector_id, shift_name, starts_at, ends_at),
    CONSTRAINT sector_shift_range_nonzero_check
        CHECK (starts_at <> ends_at)
);

CREATE INDEX sector_shift_ranges_sector_version_idx
    ON public.sector_shift_ranges (sector_id, shift_sheet_version_id);
CREATE INDEX sector_shift_ranges_lookup_idx
    ON public.sector_shift_ranges (shift_sheet_version_id, sector_id, starts_at, ends_at);

CREATE TABLE public.employees (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code text NOT NULL,
    full_name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

-- O código do funcionário continua reservado após a desativação.
CREATE UNIQUE INDEX employees_code_normalized_uq
    ON public.employees (lower(btrim(employee_code)));
CREATE INDEX employees_deleted_at_idx ON public.employees (deleted_at);

-- Modelo provisório da escala, aguardando confirmação do CSV real.
-- Cada atribuição vale para uma data específica OU para um dia da semana ISO
-- (1=segunda ... 7=domingo), dentro da versão de planilha indicada.
CREATE TABLE public.employee_shift_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_sheet_version_id integer NOT NULL,
    sector_id integer NOT NULL,
    shift_range_id integer NOT NULL,
    employee_id integer NOT NULL REFERENCES public.employees(id) ON DELETE RESTRICT,
    work_date date,
    day_of_week smallint,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT employee_shift_range_fk
        FOREIGN KEY (shift_range_id, shift_sheet_version_id, sector_id)
        REFERENCES public.sector_shift_ranges (id, shift_sheet_version_id, sector_id)
        ON DELETE RESTRICT,
    CONSTRAINT employee_shift_date_or_weekday_check CHECK (
        (work_date IS NOT NULL AND day_of_week IS NULL)
        OR (work_date IS NULL AND day_of_week IS NOT NULL)
    ),
    CONSTRAINT employee_shift_weekday_check
        CHECK (day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7)
);

CREATE UNIQUE INDEX employee_shift_date_assignment_uq
    ON public.employee_shift_assignments (shift_range_id, employee_id, work_date)
    WHERE work_date IS NOT NULL;
CREATE UNIQUE INDEX employee_shift_weekday_assignment_uq
    ON public.employee_shift_assignments (shift_range_id, employee_id, day_of_week)
    WHERE day_of_week IS NOT NULL;
CREATE INDEX employee_shift_team_lookup_idx
    ON public.employee_shift_assignments (shift_sheet_version_id, sector_id, shift_range_id);
CREATE INDEX employee_shift_employee_idx
    ON public.employee_shift_assignments (employee_id);

CREATE TABLE public.shift_upload_attempts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by_user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    attempted_at timestamptz NOT NULL DEFAULT now(),
    result public.shift_upload_result NOT NULL,
    resulting_version_id integer REFERENCES public.shift_sheet_versions(id) ON DELETE RESTRICT,
    validation_errors jsonb NOT NULL DEFAULT '[]'::jsonb,
    CONSTRAINT shift_upload_result_version_check CHECK (
        (result = 'accepted' AND resulting_version_id IS NOT NULL)
        OR (result = 'rejected' AND resulting_version_id IS NULL)
    )
);
CREATE INDEX shift_upload_attempts_created_idx
    ON public.shift_upload_attempts (attempted_at DESC);
CREATE INDEX shift_upload_attempts_user_idx
    ON public.shift_upload_attempts (uploaded_by_user_id, attempted_at DESC);

-- ---------------------------------------------------------------------------
-- Sessões anônimas, snapshot das perguntas apresentadas e respostas
-- UUID é usado apenas como identificador público da sessão de respostas.
-- As perguntas e versões são registradas no início; o mapa do front continua
-- apenas em memória e não substitui esse registro histórico no banco.
-- ---------------------------------------------------------------------------

CREATE TABLE public.submission_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    sector_id integer NOT NULL REFERENCES public.sectors(id) ON DELETE RESTRICT,
    shift_sheet_version_id integer NOT NULL,
    shift_range_id integer NOT NULL,
    started_at timestamptz NOT NULL DEFAULT now(),
    last_activity_at timestamptz NOT NULL DEFAULT now(),
    ended_at timestamptz,
    status public.submission_status NOT NULL DEFAULT 'incomplete',
    CONSTRAINT submission_session_shift_fk
        FOREIGN KEY (shift_range_id, shift_sheet_version_id, sector_id)
        REFERENCES public.sector_shift_ranges (id, shift_sheet_version_id, sector_id)
        ON DELETE RESTRICT,
    CONSTRAINT submission_session_activity_check
        CHECK (last_activity_at >= started_at),
    CONSTRAINT submission_session_end_check
        CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT submission_session_complete_end_check
        CHECK (status <> 'complete' OR ended_at IS NOT NULL)
);

CREATE INDEX submission_sessions_sector_time_idx
    ON public.submission_sessions (sector_id, started_at DESC);
CREATE INDEX submission_sessions_shift_time_idx
    ON public.submission_sessions (shift_range_id, started_at DESC);
CREATE INDEX submission_sessions_incomplete_activity_idx
    ON public.submission_sessions (last_activity_at)
    WHERE status = 'incomplete' AND ended_at IS NULL;

CREATE TABLE public.submission_session_questions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id uuid NOT NULL
        REFERENCES public.submission_sessions(id) ON DELETE RESTRICT,
    question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE RESTRICT,
    question_version_id integer NOT NULL,
    position integer NOT NULL,
    question_kind public.question_kind NOT NULL,
    is_nps boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT submission_session_question_version_fk
        FOREIGN KEY (question_version_id, question_id)
        REFERENCES public.question_versions (id, question_id)
        ON DELETE RESTRICT,
    CONSTRAINT submission_session_question_position_check CHECK (position >= 1),
    CONSTRAINT submission_session_question_position_uq UNIQUE (session_id, position),
    CONSTRAINT submission_session_question_once_uq UNIQUE (session_id, question_id)
);

CREATE INDEX submission_session_questions_session_idx
    ON public.submission_session_questions (session_id, position);
CREATE INDEX submission_session_questions_question_version_idx
    ON public.submission_session_questions (question_id, question_version_id);

CREATE TABLE public.submission_answers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_question_id integer NOT NULL UNIQUE
        REFERENCES public.submission_session_questions(id) ON DELETE RESTRICT,
    status public.answer_status NOT NULL,
    score integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    -- Integridade estrutural, sem impor aqui a escala numérica da pergunta:
    -- a API valida 1–5 para perguntas comuns e 0–10 para NPS.
    CONSTRAINT submission_answer_status_score_check CHECK (
        (status = 'answered' AND score IS NOT NULL)
        OR (status = 'skipped' AND score IS NULL)
    )
);

CREATE INDEX submission_answers_status_idx ON public.submission_answers (status);

-- ---------------------------------------------------------------------------
-- Páginas de texto e versões (inclui a página LGPD)
