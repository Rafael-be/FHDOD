-- A fila registra grupos de agregação afetados, inclusive grupos que ainda
-- não têm linha na tabela de resumo. Os services fazem UPSERT nesta fila na
-- mesma transação da alteração de negócio. A rotina horária a processa e remove
-- os itens concluídos; a role de runtime não recebe permissão de DELETE.
CREATE TABLE public.dashboard_dirty_groups (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    summary_type public.dashboard_summary_type NOT NULL,
    hour_bucket timestamptz NOT NULL,
    sector_id integer NOT NULL REFERENCES public.sectors(id) ON DELETE RESTRICT,
    shift_range_id integer NOT NULL REFERENCES public.sector_shift_ranges(id) ON DELETE RESTRICT,
    question_id integer,
    question_version_id integer,
    ticket_type public.ombudsman_ticket_type,
    ticket_status public.ombudsman_ticket_status,
    queued_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dashboard_dirty_group_question_version_fk
        FOREIGN KEY (question_version_id, question_id)
        REFERENCES public.question_versions (id, question_id)
        ON DELETE RESTRICT,
    CONSTRAINT dashboard_dirty_group_shape_check CHECK (
        (summary_type = 'answers'
            AND question_id IS NOT NULL
            AND question_version_id IS NOT NULL
            AND ticket_type IS NULL
            AND ticket_status IS NULL)
        OR
        (summary_type = 'sessions'
            AND question_id IS NULL
            AND question_version_id IS NULL
            AND ticket_type IS NULL
            AND ticket_status IS NULL)
        OR
        (summary_type = 'ombudsman'
            AND question_id IS NULL
            AND question_version_id IS NULL
            AND ticket_type IS NOT NULL
            AND ticket_status IS NOT NULL)
    )
);

