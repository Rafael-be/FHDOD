-- ============================================================================
-- FHDOD.sql — estrutura inicial do banco
-- Sistema de Avaliação da Experiência do Paciente — Hospital de Três Coroas
-- PostgreSQL / Supabase
--
-- IMPORTANTE:
-- 1. Execute este arquivo UMA ÚNICA VEZ, em um banco vazio.
-- 2. Depois do bootstrap do Drizzle, as alterações devem ocorrer por migrações.
-- 3. Não há usuário superusuário inicial aqui: sua senha precisa ser gerada com
--    Argon2 no seed TypeScript, sem senha fixa nem hash improvisado no SQL.
-- 4. A estrutura de escala por funcionário é provisória até o CSV real ser
--    confirmado com o professor. A estrutura aqui é um modelo normalizado para
--    permitir avançar sem armazenar o CSV original.
-- 5. Validações de nota e regras de transição de negócio ficam na API, conforme
--    decisão do projeto. O banco mantém as restrições estruturais e relacionais.
-- 6. Funções de recálculo do dashboard e agendamento pg_cron ficam em migração
--    SQL posterior, separada da estrutura inicial.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- Papel exclusivo para a conexão de runtime da API
-- Não é owner do schema nem pode criar/alterar estrutura. Não há senha fixa
-- no arquivo: configure-a de modo interativo fora do repositório, depois.
-- Migrações/DDL devem usar uma conexão administrativa separada.
-- ---------------------------------------------------------------------------

CREATE ROLE fhdod_api
    LOGIN
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    NOREPLICATION
    NOBYPASSRLS;

-- ---------------------------------------------------------------------------
-- Tipos enumerados
-- ---------------------------------------------------------------------------

