CREATE TABLE IF NOT EXISTS shift_sheet_versions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imported_at timestamptz NOT NULL,
  is_current boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX IF NOT EXISTS shift_sheet_versions_one_current_uq
  ON shift_sheet_versions (is_current) WHERE is_current = true;

CREATE TABLE IF NOT EXISTS sector_shift_ranges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_sheet_version_id integer NOT NULL REFERENCES shift_sheet_versions(id),
  sector_id integer NOT NULL REFERENCES sectors(id),
  shift_name text NOT NULL,
  starts_at time NOT NULL,
  ends_at time NOT NULL,
  employee_code text NOT NULL,
  employee_name text NOT NULL,
  day_of_week integer NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT sector_shift_ranges_distinct_hours_ck CHECK (starts_at <> ends_at),
  CONSTRAINT sector_shift_ranges_unique_shift_day_uq UNIQUE (shift_sheet_version_id, sector_id, shift_name, day_of_week)
);

CREATE INDEX IF NOT EXISTS sector_shift_ranges_version_sector_idx
  ON sector_shift_ranges (shift_sheet_version_id, sector_id, day_of_week);
