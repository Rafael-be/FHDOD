CREATE TABLE IF NOT EXISTS shift_sheet_versions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_number integer NOT NULL UNIQUE CHECK (version_number >= 1),
  uploaded_by_user_id integer REFERENCES users(id) ON DELETE RESTRICT,
  uploaded_at timestamptz NOT NULL DEFAULT now(),
  valid_from timestamptz NOT NULL DEFAULT now(),
  is_current boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX IF NOT EXISTS shift_sheet_versions_one_current_uq
  ON shift_sheet_versions (is_current) WHERE is_current = true;

CREATE TABLE IF NOT EXISTS sector_shift_ranges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_sheet_version_id integer NOT NULL REFERENCES shift_sheet_versions(id),
  sector_id integer NOT NULL REFERENCES sectors(id),
  shift_name text NOT NULL,
  starts_at time NOT NULL,
  ends_at time NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  day_of_week integer NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT sector_shift_ranges_distinct_hours_ck CHECK (starts_at <> ends_at),
  CONSTRAINT sector_shift_range_duplicate_uq UNIQUE (shift_sheet_version_id, sector_id, shift_name, starts_at, ends_at)
);

CREATE INDEX IF NOT EXISTS sector_shift_ranges_version_sector_idx
  ON sector_shift_ranges (shift_sheet_version_id, sector_id, day_of_week);

CREATE TABLE IF NOT EXISTS employees (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_code text NOT NULL,
  full_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS employees_code_normalized_uq ON employees (lower(btrim(employee_code)));

CREATE TABLE IF NOT EXISTS employee_shift_assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_sheet_version_id integer NOT NULL REFERENCES shift_sheet_versions(id) ON DELETE RESTRICT,
  sector_id integer NOT NULL REFERENCES sectors(id) ON DELETE RESTRICT,
  shift_range_id integer NOT NULL REFERENCES sector_shift_ranges(id) ON DELETE RESTRICT,
  employee_id integer NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
  work_date date,
  day_of_week integer CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT employee_shift_date_or_weekday_check CHECK ((work_date IS NOT NULL AND day_of_week IS NULL) OR (work_date IS NULL AND day_of_week IS NOT NULL))
);
